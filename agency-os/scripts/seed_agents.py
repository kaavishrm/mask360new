"""Write db/seed_agents.sql: the agent registry (desk, order, job) the control room draws.

Usage: python3 agency-os/scripts/seed_agents.py
Edit DESKS when an agent is added, moved or removed, rerun, and apply the SQL.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
DESKS = [
    ("Command", ["chief", "gatekeeper", "auditor", "think", "verify", "do"]),
    ("Inbox", ["inbox", "calendar"]),
    ("Hunt", ["scout", "scorer", "finder", "enricher"]),
    ("Reach", ["apollo", "linkedin", "whatsapp", "rooms", "consultants", "referrals"]),
    ("Convert", ["responder", "qualifier", "booker", "dossier", "diagnostic", "proposer", "pricer", "negotiator", "pitch"]),
    ("Contract", ["contracts", "empanel"]),
    ("Deliver", ["onboarder", "planner", "copywriter", "designer", "publisher", "community", "performance", "reporter", "pr", "creators", "producer", "events", "guestlist", "vendors"]),
    ("Client", ["status", "chaser", "ideas", "health", "scope", "qbr", "growth"]),
    ("Money", ["invoicer", "collector", "payables", "bookkeeper", "tax", "cfo"]),
    ("People", ["capacity", "recruiter"]),
    ("Agency", ["founder", "cases", "awards", "admin"]),
]
ROLES = {"think", "verify", "do"}  # the three cluster roles: listed under Command, drawn inside every agent

rows = []
for di, (desk, names) in enumerate(DESKS, 1):
    for pi, n in enumerate(names, 1):
        if n in ROLES:
            continue
        text = (ROOT / ".claude" / "agents" / f"os-{n}.md").read_text(encoding="utf-8")
        desc = re.search(r"^description: (.+)$", text, re.M).group(1)
        job = desc.split(". ")[0].rstrip(".")
        if len(job) > 140:
            job = job[:137].rsplit(" ", 1)[0] + "..."
        rows.append(f"('os-{n}','{desk}',{di},{pi},'{job.replace(chr(39), chr(39) * 2)}')")

sql = ("-- Generated by scripts/seed_agents.py. Do not edit by hand.\n"
       "insert into os.agents (org_id,name,desk,desk_order,position,job)\n"
       "select o.id, v.name, v.desk, v.desk_order, v.position, v.job from os.orgs o, (values\n"
       + ",\n".join(rows)
       + "\n) as v(name,desk,desk_order,position,job) where o.slug='mask360'\n"
       "on conflict (org_id,name) do update set desk=excluded.desk, desk_order=excluded.desk_order, position=excluded.position, job=excluded.job;\n")
(ROOT / "agency-os" / "db" / "seed_agents.sql").write_text(sql, encoding="utf-8")
print(f"{len(rows)} agents written to db/seed_agents.sql")
